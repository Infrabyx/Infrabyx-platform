#!/usr/bin/env node
// pnpm exit-runbook (IPB-01 §01.4.13, IPB-01-38; PL6 plan §9.2): writes docs/exit/EXIT_RUNBOOK.md from
// the port catalogue's RTO tiers (`@infrabyx/contracts`), the adapter exit metadata
// (`@infrabyx/connectors/exit`), a routing file (the deployment's primary and secondary adapters)
// and the drill records. A product runs it over its own routing file.
//   node scripts/exit-runbook.mjs [--routing <file>] [--drills <file>] [--out <file>]
//   node scripts/exit-runbook.mjs --check              # the file matches the generator (drift)
//   node scripts/exit-runbook.mjs --max-age-days 180   # the release gate (@IPB-01-AT-17)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { parseArgs } from "node:util";
import { parse as parseYaml } from "yaml";

const ROOT = new URL("..", import.meta.url).pathname;

/** Target RTO by tier (IPB-01 §01.4.13). */
export const TARGET_RTO = {
  0: "24 h",
  1: "48 h",
  2: "8 h (configuration swap)",
  3: "4 h",
};

const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");
const day = (d) => d.toISOString().slice(0, 10);

/** The latest drill per port from the drill records. */
function latestDrills(drills) {
  const out = new Map();
  for (const d of drills ?? []) {
    const cur = out.get(d.port);
    if (!cur || d.date > cur.date) out.set(d.port, d);
  }
  return out;
}

/** The runbook as Markdown. Pure: the inputs and the date decide it. */
export function renderRunbook({ catalogue, exits, routing, drills, sources, generatedOn }) {
  const latest = latestDrills(drills);
  const rows = exits.map((e) => {
    const r = routing?.ports?.[e.port];
    const primary = r?.primary?.adapter ?? e.primary;
    const target = r?.secondary?.adapter ?? e.exitTarget;
    const tier = catalogue[e.port]?.tier;
    if (tier === undefined) throw new Error(`${e.port} is not in the port catalogue`);
    const d = latest.get(e.port);
    return [
      `${e.port} / ${primary}`,
      target,
      e.dataMove,
      e.volumeClass,
      d ? `${d.measuredRtoHours} h` : "Not yet drilled",
      `Tier ${tier}: ${TARGET_RTO[tier]}`,
      e.lockIn,
      d ? `${d.date}, ${d.env}, ${d.evidence}` : "None",
    ];
  });
  return [
    "# Exit runbook",
    "",
    `Generated: ${generatedOn}`,
    "",
    `Generated by \`pnpm exit-runbook\` from the port catalogue (\`@infrabyx/contracts\`), the adapter exit metadata (\`@infrabyx/connectors/exit\`), ${sources.routing ? `\`${sources.routing}\`` : "the reference adapters"} and \`${sources.drills}\`. Do not edit by hand. Regenerate at every release; the release job refuses a runbook older than 180 days (IPB-01-38, @IPB-01-AT-17).`,
    "",
    "## Ports",
    "",
    "| Port / current primary | Exit target | Data move method | Data volume class | Measured RTO | Target RTO | Lock-in residue | Last drill |",
    "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`),
    "",
    "Data volume class: S under 100 GB, M under 1 TB, L over 1 TB. Measured RTO and the last drill come from the drill records; a port without a drill shows its target only.",
    "",
    "## Whole-cloud exit",
    "",
    "The OpenTofu stacks of `infra/terraform/envs/<product>/<env>` are re-pointed at the other cloud's modules and their outputs regenerate the routing file; the database moves by logical replication, storage by `replicateTo` with manifest verification, identity by provisioning users at the target, and workflows drain on the source while new executions start on the target. The target for a full-cloud move of a product under 1 TB is five working days, drilled in `staging` every 24 months. Regulated clients receive this runbook with the tenant export (`<PRODUCT>-EXPORT-1.0`).",
    "",
  ].join("\n");
}

/** The `Generated:` date of a runbook file, or null. */
export function generatedOn(text) {
  return /^Generated: (\d{4}-\d{2}-\d{2})$/m.exec(text)?.[1] ?? null;
}

async function loadInputs(o) {
  const { PORT_CATALOGUE } = await import(join(ROOT, "packages/contracts/dist/ports/catalogue.js"));
  const { PORT_EXIT } = await import(join(ROOT, "packages/connectors/dist/exit.js"));
  const routing = o.routing ? parseYaml(readFileSync(o.routing, "utf8")) : null;
  const drills = existsSync(o.drills) ? JSON.parse(readFileSync(o.drills, "utf8")).drills : [];
  return { catalogue: PORT_CATALOGUE, exits: PORT_EXIT, routing, drills };
}

async function main(argv) {
  const { values } = parseArgs({
    args: argv,
    options: {
      routing: { type: "string", default: join(ROOT, "infra/routing/reference/ci.routing.yaml") },
      drills: { type: "string", default: join(ROOT, "docs/exit/drills.json") },
      out: { type: "string", default: join(ROOT, "docs/exit/EXIT_RUNBOOK.md") },
      now: { type: "string" },
      check: { type: "boolean", default: false },
      "max-age-days": { type: "string" },
    },
  });
  const now = values.now ? new Date(values.now) : new Date();
  const existing = existsSync(values.out) ? readFileSync(values.out, "utf8") : null;
  if (values["max-age-days"] !== undefined) {
    const max = Number(values["max-age-days"]);
    const on = existing ? generatedOn(existing) : null;
    if (!on)
      return fail(`${values.out} is missing or has no Generated date; run pnpm exit-runbook`);
    const age = Math.floor((now.getTime() - Date.parse(`${on}T00:00:00Z`)) / 86_400_000);
    if (age > max)
      return fail(
        `${values.out} was generated ${age} days ago (${on}), more than ${max}: run pnpm exit-runbook and commit it (IPB-01-38)`,
      );
    console.log(`exit runbook generated ${on}, ${age} days ago (limit ${max})`);
    return 0;
  }
  const inputs = await loadInputs(values);
  const sources = {
    routing: values.routing ? relative(ROOT, values.routing) : null,
    drills: relative(ROOT, values.drills),
  };
  if (values.check) {
    const on = existing ? generatedOn(existing) : null;
    if (!on) return fail(`${values.out} is missing; run pnpm exit-runbook`);
    if (renderRunbook({ ...inputs, sources, generatedOn: on }) !== existing)
      return fail(
        `${values.out} is out of date with its inputs; run pnpm exit-runbook and commit it`,
      );
    console.log(
      `${relative(ROOT, values.out)} matches the port catalogue and the adapter metadata`,
    );
    return 0;
  }
  mkdirSync(dirname(values.out), { recursive: true });
  writeFileSync(values.out, renderRunbook({ ...inputs, sources, generatedOn: day(now) }));
  console.log(`wrote ${relative(ROOT, values.out)} (${inputs.exits.length} ports)`);
  return 0;
}

function fail(msg) {
  console.error(`exit-runbook: ${msg}`);
  return 1;
}

if (import.meta.url === `file://${process.argv[1]}`)
  process.exitCode = await main(process.argv.slice(2));
export { main };

// Generates migrations/0003_pgboss.sql from pg-boss's own construction plan (PL2 plan §6.8,
// PL2-D-58). Run once per pg-boss schema version: `node scripts/gen-pgboss-migration.mjs`.
// The migration runner wraps each file in a transaction, so pg-boss's BEGIN/COMMIT go; the
// runtime starts with `migrate: false` and `createSchema: false` because application roles have
// no DDL rights. Every column gets a data-class comment for migration-lint: the queue holds IDs
// and INTERNAL scalars only (QueueJobData), so the schema is INTERNAL.
import { writeFileSync } from "node:fs";
import { getConstructionPlans } from "pg-boss";

const SCHEMA = "pgboss";
const raw = getConstructionPlans(SCHEMA);
const body = raw
  .split("\n")
  .filter((l) => !/^\s*(BEGIN|COMMIT);\s*$/.test(l) && !/^\s*SET LOCAL /.test(l))
  .join("\n")
  .trim();

const tables = [
  ...body.matchAll(
    /CREATE TABLE (?:IF NOT EXISTS )?pgboss\.(\w+)\s*\(([^;]*?)\n\s*\)\s*(?:PARTITION BY[^;]*)?;/g,
  ),
];
const comments = [];
for (const [, table, cols] of tables) {
  if (/^\s*LIKE /.test(cols)) continue;
  for (const line of cols.split("\n")) {
    const m = /^\s*([a-z_][a-z0-9_]*)\s+(?!KEY\b)[a-z]/i.exec(line);
    if (!m || /^(PRIMARY|CONSTRAINT|UNIQUE|CHECK|FOREIGN|EXCLUDE)$/i.test(m[1])) continue;
    comments.push(`comment on column ${SCHEMA}.${table}.${m[1]} is 'dataclass:INTERNAL';`);
  }
}

const out = `-- @infrabyx/connectors 0003: pg-boss ${raw.match(/version\(version\) VALUES \('(\d+)'\)/)?.[1] ?? "?"} schema for the QUEUE alternative \`pg-boss\` (PL2 plan §6.8,
-- D-05, PL2-D-58). Generated by scripts/gen-pgboss-migration.mjs from pg-boss's construction plan;
-- do not edit by hand. Expand-only. Queue payloads are IDs and INTERNAL scalars (QueueJobData), so
-- the tables carry no tenant column and no RLS: tenant context is rebuilt by the consumer from the
-- IDs. Application roles get DML and EXECUTE only; pg-boss runs with migrate and createSchema off.
set lock_timeout = '5s';
set statement_timeout = '60s';

${body}

${comments.join("\n")}

revoke all on schema ${SCHEMA} from public;
grant usage on schema ${SCHEMA} to app_rw;
grant select, insert, update, delete on all tables in schema ${SCHEMA} to app_rw;
grant execute on all functions in schema ${SCHEMA} to app_rw;
grant usage on type ${SCHEMA}.job_state to app_rw;
`;
writeFileSync(new URL("../migrations/0003_pgboss.sql", import.meta.url), out);
console.log(`wrote 0003_pgboss.sql (${tables.length} tables, ${comments.length} column comments)`);

// IDENTITY customer sign-in on Keycloak (OWNER-QUESTIONS #84 (b), R1-D-19): one customer realm per
// product, separate from every staff realm, on the Keycloak image with the `ipb-customer-otp`
// extension (infra/keycloak/customer-otp). The realm's direct-grant flow is username, then the
// one-time-code step; its API client is confidential and DPoP-bound (`dpop.bound.access.tokens`),
// so Keycloak itself binds each access token to the device key (`cnf.jkt`). Keycloak returns each
// code to the API client, which delivers it through NOTIFY; Keycloak keeps only a hash of it.
// Usernames are derived from the tenant and the login (`cus` + 40 hex), so one person is one
// account per tenant and the login is never a username. The realm carries no `amr` mapper: a
// one-time code is not MFA (IPB-02-02).
import { IpbError, PortError } from "@infrabyx/contracts/errors";
import type {
  AdapterDescriptor,
  CustomerOtpChannel,
  DpopTarget,
  PortHealth,
} from "@infrabyx/contracts";
import { sha256Hex } from "@infrabyx/crypto";
import type { createEgress, EgressResponse } from "../core/http.js";
import { TokenVerifier } from "./common.js";
import {
  CustomerIdentityBase,
  customerIdentitySettings,
  type ChallengeRecord,
  type CustomerIdentityBaseOptions,
  type CustomerIdentitySettings,
  type IdpTokens,
} from "./customer.js";
import { keycloakEgress } from "./keycloak.js";

type Egress = ReturnType<typeof createEgress>;

/** The flow and the extension's provider id. */
export const KEYCLOAK_CUSTOMER_FLOW = "ipb-customer-otp";
export const KEYCLOAK_CUSTOMER_OTP_PROVIDER = "ipb-customer-otp";

/** Username of a customer account: one per tenant and login, never the login itself. */
export const keycloakCustomerUsername = (tenantId: string, login: string): string =>
  `cus${sha256Hex(`${tenantId}:${login}`).slice(0, 40)}`;

export interface KeycloakCustomerRealmSpec {
  /** e.g. `udf-customers`; never a staff realm. */
  realm: string;
  /** The product API's client: direct grant only, confidential, DPoP-bound. */
  apiClientId: string;
  /** Service account the adapter uses for the Admin API (user management only). */
  adminClientId: string;
  /** Audience the API accepts (`aud`). */
  audience: string;
  /** Product roles customers may hold (e.g. UDF_BORROWER). */
  customerRoles?: readonly string[];
  settings?: Partial<CustomerIdentitySettings>;
}

/** The realm settings the customer profile fixes (contract test: read back equal). */
export function keycloakCustomerRealmSettings(s: CustomerIdentitySettings) {
  return {
    defaultSignatureAlgorithm: "ES256",
    accessTokenLifespan: 300,
    revokeRefreshToken: true,
    refreshTokenMaxReuse: 0,
    ssoSessionIdleTimeout: s.sessionIdleSeconds,
    ssoSessionMaxLifespan: s.sessionMaxSeconds,
    registrationAllowed: false,
    resetPasswordAllowed: false,
    loginWithEmailAllowed: false,
    duplicateEmailsAllowed: true,
    editUsernameAllowed: false,
    rememberMe: false,
    sslRequired: "external",
    bruteForceProtected: true,
    permanentLockout: false,
    failureFactor: s.lockoutAfterFailures,
    waitIncrementSeconds: 60,
    maxFailureWaitSeconds: s.lockoutSeconds,
    maxDeltaTimeSeconds: s.sendWindowSeconds,
  } as const;
}

/** The customer realm as configuration as code. Secrets are generated by Keycloak, never here. */
export function ipbCustomerRealm(spec: KeycloakCustomerRealmSpec): Record<string, unknown> {
  const s = customerIdentitySettings(spec.settings);
  const mapper = (name: string, protocolMapper: string, config: Record<string, string>) => ({
    name,
    protocol: "openid-connect",
    protocolMapper,
    config: { "access.token.claim": "true", "id.token.claim": "false", ...config },
  });
  const attr = (claim: string, attribute: string) =>
    mapper(claim, "oidc-usermodel-attribute-mapper", {
      "user.attribute": attribute,
      "claim.name": claim,
      "jsonType.label": "String",
      multivalued: "false",
      "userinfo.token.claim": "false",
    });
  return {
    realm: spec.realm,
    enabled: true,
    ...keycloakCustomerRealmSettings(s),
    roles: { realm: (spec.customerRoles ?? []).map((name) => ({ name })) },
    components: {
      "org.keycloak.keys.KeyProvider": [
        {
          name: "ipb-es256",
          providerId: "ecdsa-generated",
          subComponents: {},
          config: {
            priority: ["200"],
            enabled: ["true"],
            active: ["true"],
            ecdsaEllipticCurveKey: ["P-256"],
          },
        },
      ],
    },
    clients: [
      {
        clientId: spec.apiClientId,
        protocol: "openid-connect",
        publicClient: false,
        standardFlowEnabled: false,
        implicitFlowEnabled: false,
        directAccessGrantsEnabled: true,
        serviceAccountsEnabled: false,
        frontchannelLogout: false,
        fullScopeAllowed: true,
        attributes: {
          "dpop.bound.access.tokens": "true",
          "ipb.customer.otp": "true",
          "access.token.signed.response.alg": "ES256",
          "use.refresh.tokens": "true",
          "client_credentials.use_refresh_token": "false",
        },
        protocolMappers: [
          attr("tid", "tenant_id"),
          attr("ptyp", "principal_type"),
          mapper("roles", "oidc-usermodel-realm-role-mapper", {
            "claim.name": "roles",
            "jsonType.label": "String",
            multivalued: "true",
            "userinfo.token.claim": "false",
          }),
          mapper("audience", "oidc-audience-mapper", {
            "included.custom.audience": spec.audience,
          }),
        ],
      },
      {
        clientId: spec.adminClientId,
        protocol: "openid-connect",
        publicClient: false,
        standardFlowEnabled: false,
        directAccessGrantsEnabled: false,
        serviceAccountsEnabled: true,
        attributes: { "access.token.signed.response.alg": "ES256" },
      },
    ],
  };
}

export interface KeycloakCustomerIdentityOptions extends CustomerIdentityBaseOptions {
  /** Base URL, e.g. https://id.example.in (without `/realms/<realm>`). */
  baseUrl: string;
  realm: string;
  clientId: string;
  clientSecret: string;
  adminClientId: string;
  adminClientSecret: string;
  audience: string;
  jwksCacheSeconds?: number;
  allowLoopbackHttp?: boolean;
}

interface KcUser {
  id: string;
  username: string;
  enabled: boolean;
  attributes?: Record<string, string[]>;
}

export class KeycloakCustomerIdentity extends CustomerIdentityBase {
  readonly descriptor: AdapterDescriptor = {
    port: "IDENTITY",
    adapter: "keycloak-customer",
    residency: "IN",
    maxDataClass: "CONFIDENTIAL",
    capabilities: { "customer.dpopBinding": "native" },
  };
  readonly issuer: string;
  readonly signInProofTarget: DpopTarget;
  protected readonly nativeBinding = true;
  protected readonly verifier: TokenVerifier;
  private readonly egress: Egress;
  private adminToken: { value: string; until: number } | null = null;

  constructor(private readonly o: KeycloakCustomerIdentityOptions) {
    super(o);
    const base = o.baseUrl.replace(/\/$/, "");
    this.issuer = `${base}/realms/${o.realm}`;
    this.signInProofTarget = { htm: "POST", htu: `${this.issuer}/protocol/openid-connect/token` };
    this.egress = keycloakEgress(base, o.allowLoopbackHttp);
    this.verifier = new TokenVerifier({
      issuer: this.issuer,
      audience: o.audience,
      jwksUrl: `${this.issuer}/protocol/openid-connect/certs`,
      egress: this.egress,
      algorithms: ["ES256"],
      ...(o.jwksCacheSeconds !== undefined ? { jwksCacheSeconds: o.jwksCacheSeconds } : {}),
      revocations: o.revocations,
      ...(o.now ? { now: o.now } : {}),
    });
  }

  private fail(status: number, what: string): never {
    throw new PortError(
      status === 401 || status === 403 ? "IPB-PORT-001" : "IPB-PORT-002",
      "IDENTITY",
      {
        adapter: "keycloak-customer",
        detail: `${what} answered ${status}`,
        meta: { status },
      },
    );
  }

  private unavailable(cause?: unknown): never {
    throw new PortError("IPB-IDN-002", "IDENTITY", {
      adapter: "keycloak-customer",
      detail: "identity provider unavailable for new sessions",
      ...(cause ? { cause } : {}),
    });
  }

  private async token(form: Record<string, string>, dpopProof?: string): Promise<EgressResponse> {
    return this.egress(this.signInProofTarget.htu, {
      method: "POST",
      headers: {
        "content-type": "application/x-www-form-urlencoded",
        ...(dpopProof ? { dpop: dpopProof } : {}),
      },
      body: new URLSearchParams({
        client_id: this.o.clientId,
        client_secret: this.o.clientSecret,
        ...form,
      }).toString(),
    }).catch((e: unknown) => this.unavailable(e));
  }

  private async admin(): Promise<string> {
    if (this.adminToken && this.now < this.adminToken.until) return this.adminToken.value;
    const r = await this.egress(this.signInProofTarget.htu, {
      method: "POST",
      headers: { "content-type": "application/x-www-form-urlencoded" },
      body: new URLSearchParams({
        grant_type: "client_credentials",
        client_id: this.o.adminClientId,
        client_secret: this.o.adminClientSecret,
      }).toString(),
    });
    if (r.status !== 200) this.fail(r.status, "admin token");
    const t = r.json<{ access_token: string; expires_in: number }>();
    this.adminToken = {
      value: t.access_token,
      until: this.now + Math.max(0, t.expires_in - 30) * 1000,
    };
    return t.access_token;
  }

  private async api<T>(
    method: string,
    path: string,
    body?: unknown,
  ): Promise<{ status: number; data: T; headers: Headers }> {
    const r = await this.egress(
      `${this.o.baseUrl.replace(/\/$/, "")}/admin/realms/${this.o.realm}${path}`,
      {
        method,
        headers: {
          authorization: `Bearer ${await this.admin()}`,
          "content-type": "application/json",
        },
        ...(body === undefined ? {} : { body: JSON.stringify(body) }),
      },
    );
    if (r.status >= 300 && r.status !== 409 && r.status !== 404)
      this.fail(r.status, `${method} ${path.split("?")[0]!.split("/").slice(0, 2).join("/")}`);
    return {
      status: r.status,
      data: (r.body.byteLength ? r.json<T>() : undefined) as T,
      headers: r.headers,
    };
  }

  private async byUsername(username: string): Promise<KcUser | undefined> {
    const { data } = await this.api<KcUser[]>(
      "GET",
      `/users?exact=true&briefRepresentation=false&username=${username}`,
    );
    return data.find((u) => u.username === username);
  }

  protected async resolveUser(
    tenantId: string,
    _channel: CustomerOtpChannel,
    login: string,
  ): Promise<string> {
    const username = keycloakCustomerUsername(tenantId, login);
    const found = await this.byUsername(username);
    if (found) return found.id;
    const created = await this.api("POST", "/users", {
      username,
      enabled: true,
      attributes: {
        tenant_id: [tenantId],
        principal_type: ["user"],
        customer_login: [login],
      },
    });
    const id =
      created.status === 201
        ? created.headers.get("location")?.split("/").pop()
        : (await this.byUsername(username))?.id; // 409: created by a concurrent request
    if (!id) this.fail(created.status, "create customer");
    if (created.status === 201 && this.base.customerRoles?.length) {
      const roles = [];
      for (const name of this.base.customerRoles)
        roles.push(
          (
            await this.api<{ id: string; name: string }>(
              "GET",
              `/roles/${encodeURIComponent(name)}`,
            )
          ).data,
        );
      await this.api("POST", `/users/${id}/role-mappings/realm`, roles);
    }
    return id!;
  }

  protected async idpSend(
    a: { tenantId: string; userId: string; login: string; channel: CustomerOtpChannel },
    dpopProof: string,
  ): Promise<{ ref: Record<string, string>; code: string }> {
    const username = keycloakCustomerUsername(a.tenantId, a.login);
    const r = await this.token(
      { grant_type: "password", username, ipb_otp_step: "send" },
      dpopProof,
    );
    if (r.status >= 500) this.unavailable();
    if (r.status !== 202) {
      // The realm's own brute-force protection, or a disabled account.
      if (r.status === 400 || r.status === 401)
        throw new IpbError("IPB-SEC-019", {
          detail: "the identity provider refused a code for this account now",
          meta: { reason: "idp_refused", retryAfterSeconds: 60 },
        });
      this.fail(r.status, "send code");
    }
    const b = r.json<{ ipb_otp_challenge?: unknown; ipb_otp_code?: unknown }>();
    if (typeof b.ipb_otp_challenge !== "string" || typeof b.ipb_otp_code !== "string")
      this.fail(r.status, "send code without a challenge (is the extension installed?)");
    return {
      ref: { challenge: b.ipb_otp_challenge as string, username },
      code: b.ipb_otp_code as string,
    };
  }

  private tokens(r: EgressResponse): IdpTokens {
    const t = r.json<{
      access_token: string;
      refresh_token?: string;
      expires_in: number;
      token_type?: string;
    }>();
    if (!t.refresh_token || t.token_type?.toLowerCase() !== "dpop")
      this.fail(r.status, "token without a DPoP binding or a refresh token");
    return { accessToken: t.access_token, refreshToken: t.refresh_token!, expiresIn: t.expires_in };
  }

  protected async idpVerify(
    c: ChallengeRecord,
    code: string,
    dpopProof: string,
  ): Promise<IdpTokens | null> {
    const r = await this.token(
      {
        grant_type: "password",
        username: c.idpRef.username!,
        ipb_otp_step: "verify",
        ipb_otp_challenge: c.idpRef.challenge!,
        ipb_otp_code: code,
      },
      dpopProof,
    );
    if (r.status >= 500) this.unavailable();
    if (r.status !== 200) return null;
    return this.tokens(r);
  }

  protected async idpRefresh(refreshToken: string, dpopProof: string): Promise<IdpTokens | null> {
    const r = await this.token(
      { grant_type: "refresh_token", refresh_token: refreshToken },
      dpopProof,
    );
    if (r.status >= 500) this.unavailable();
    if (r.status !== 200) return null;
    return this.tokens(r);
  }

  protected async idpEndSession(_userId: string, session: string): Promise<void> {
    await this.api("DELETE", `/sessions/${encodeURIComponent(session)}`);
  }

  async health(): Promise<PortHealth> {
    const t0 = Date.now();
    let status: PortHealth["status"];
    try {
      const r = await this.egress(`${this.issuer}/.well-known/openid-configuration`);
      status = r.status === 200 ? "up" : "down";
    } catch {
      status = "down";
    }
    return { status, latency_ms: Date.now() - t0, checked_at: new Date().toISOString() };
  }

  /** The realm settings the customer profile fixes, as Keycloak reports them. */
  async readRealmSettings(): Promise<Record<string, unknown>> {
    const r = await this.egress(
      `${this.o.baseUrl.replace(/\/$/, "")}/admin/realms/${this.o.realm}`,
      {
        headers: { authorization: `Bearer ${await this.admin()}` },
      },
    );
    if (r.status !== 200) this.fail(r.status, "GET realm");
    const realm = r.json<Record<string, unknown>>();
    return Object.fromEntries(
      Object.keys(keycloakCustomerRealmSettings(this.s)).map((k) => [k, realm[k]]),
    );
  }

  /**
   * Create or update the customer realm with a master-realm admin token (deploy jobs and tests
   * only). Fails when the Keycloak image lacks the extension. Returns the generated client secrets
   * for the SECRETS port; secrets are returned, never logged.
   */
  static async applyCustomerRealm(o: {
    baseUrl: string;
    masterAdmin: { username: string; password: string };
    spec: KeycloakCustomerRealmSpec;
    allowLoopbackHttp?: boolean;
  }): Promise<{ clientSecret: string; adminClientSecret: string }> {
    const base = o.baseUrl.replace(/\/$/, "");
    const egress = keycloakEgress(base, o.allowLoopbackHttp);
    const fail = (status: number, what: string): never => {
      throw new PortError("IPB-PORT-002", "IDENTITY", {
        adapter: "keycloak-customer",
        detail: `${what} answered ${status}`,
      });
    };
    const tr = await egress(`${base}/realms/master/protocol/openid-connect/token`, {
      method: "POST",
      headers: { "content-type": "application/x-www-form-urlencoded" },
      body: new URLSearchParams({
        grant_type: "password",
        client_id: "admin-cli",
        username: o.masterAdmin.username,
        password: o.masterAdmin.password,
      }).toString(),
    });
    if (tr.status !== 200) fail(tr.status, "master admin token");
    const token = tr.json<{ access_token: string }>().access_token;
    const call = async <T>(method: string, path: string, body?: unknown): Promise<T> => {
      const r = await egress(`${base}/admin${path}`, {
        method,
        headers: { authorization: `Bearer ${token}`, "content-type": "application/json" },
        ...(body === undefined ? {} : { body: JSON.stringify(body) }),
      });
      if (r.status >= 300)
        fail(r.status, `${method} /admin${path.split("/").slice(0, 4).join("/")}`);
      return (r.body.byteLength ? r.json<T>() : undefined) as T;
    };
    const providers = await call<{
      providers?: Record<string, { providers?: Record<string, unknown> }>;
    }>("GET", "/serverinfo");
    if (!providers.providers?.authenticator?.providers?.[KEYCLOAK_CUSTOMER_OTP_PROVIDER])
      fail(501, "this Keycloak has no ipb-customer-otp extension (infra/keycloak/customer-otp)");

    const realm = o.spec.realm;
    const s = customerIdentitySettings(o.spec.settings);
    const rep = ipbCustomerRealm(o.spec);
    const exists = await egress(`${base}/admin/realms/${realm}`, {
      headers: { authorization: `Bearer ${token}` },
    });
    if (exists.status === 404) await call("POST", "/realms", rep);
    else {
      const { roles: _r, clients: _c, components: _k, ...settings } = rep;
      await call("PUT", `/realms/${realm}`, settings);
    }
    const R = `/realms/${realm}`;

    // Attributes are admin-only (IPB-02-13); no name or email is required of a customer.
    const profile = await call<{
      attributes: Array<Record<string, unknown> & { name: string }>;
      unmanagedAttributePolicy?: string;
    }>("GET", `${R}/users/profile`);
    profile.unmanagedAttributePolicy = "ADMIN_EDIT";
    for (const a of profile.attributes)
      if (a.name === "firstName" || a.name === "lastName" || a.name === "email") delete a.required;
    await call("PUT", `${R}/users/profile`, profile);

    // The direct-grant flow: username, then the one-time code.
    const flows = await call<Array<{ id: string; alias: string }>>(
      "GET",
      `${R}/authentication/flows`,
    );
    let flow = flows.find((f) => f.alias === KEYCLOAK_CUSTOMER_FLOW);
    if (!flow) {
      await call("POST", `${R}/authentication/flows`, {
        alias: KEYCLOAK_CUSTOMER_FLOW,
        description: "Infrabyx customer sign-in: username, then a one-time code (R1-D-19)",
        providerId: "basic-flow",
        topLevel: true,
        builtIn: false,
      });
      for (const provider of ["direct-grant-validate-username", KEYCLOAK_CUSTOMER_OTP_PROVIDER])
        await call(
          "POST",
          `${R}/authentication/flows/${KEYCLOAK_CUSTOMER_FLOW}/executions/execution`,
          { provider },
        );
      flow = (
        await call<Array<{ id: string; alias: string }>>("GET", `${R}/authentication/flows`)
      ).find((f) => f.alias === KEYCLOAK_CUSTOMER_FLOW)!;
    }
    const execs = await call<
      Array<{ id: string; providerId?: string; requirement: string; authenticationConfig?: string }>
    >("GET", `${R}/authentication/flows/${KEYCLOAK_CUSTOMER_FLOW}/executions`);
    const config = { ttl: String(s.codeTtlSeconds), attempts: String(s.attemptsPerCode) };
    for (const e of execs) {
      if (e.requirement !== "REQUIRED")
        await call("PUT", `${R}/authentication/flows/${KEYCLOAK_CUSTOMER_FLOW}/executions`, {
          ...e,
          requirement: "REQUIRED",
        });
      if (e.providerId !== KEYCLOAK_CUSTOMER_OTP_PROVIDER) continue;
      if (!e.authenticationConfig)
        await call("POST", `${R}/authentication/executions/${e.id}/config`, {
          alias: `ipb-customer-otp-${e.id.slice(0, 8)}`,
          config,
        });
      else {
        const cur = await call<Record<string, unknown>>(
          "GET",
          `${R}/authentication/config/${e.authenticationConfig}`,
        );
        await call("PUT", `${R}/authentication/config/${e.authenticationConfig}`, {
          ...cur,
          config,
        });
      }
    }

    // Bind the API client to the flow; on an existing realm, bring the client's settings back too.
    const clients = await call<Array<Record<string, unknown> & { id: string; clientId: string }>>(
      "GET",
      `${R}/clients`,
    );
    const want = (rep.clients as Array<Record<string, unknown>>).find(
      (c) => c.clientId === o.spec.apiClientId,
    )!;
    const api = clients.find((c) => c.clientId === o.spec.apiClientId);
    if (api) {
      const { protocolMappers: _m, ...wanted } = want;
      await call("PUT", `${R}/clients/${api.id}`, {
        ...api,
        ...wanted,
        attributes: {
          ...(api.attributes as Record<string, string>),
          ...(want.attributes as Record<string, string>),
        },
        authenticationFlowBindingOverrides: { direct_grant: flow.id },
      });
    }
    const id = (cid: string) => clients.find((c) => c.clientId === cid)!.id;
    const rm = id("realm-management");
    const sa = await call<{ id: string }>(
      "GET",
      `${R}/clients/${id(o.spec.adminClientId)}/service-account-user`,
    );
    const available = await call<Array<{ id: string; name: string }>>(
      "GET",
      `${R}/clients/${rm}/roles`,
    );
    await call(
      "POST",
      `${R}/users/${sa.id}/role-mappings/clients/${rm}`,
      available.filter((r) =>
        ["manage-users", "view-users", "query-users", "view-realm"].includes(r.name),
      ),
    );
    const secret = async (cid: string) =>
      (await call<{ value: string }>("GET", `${R}/clients/${id(cid)}/client-secret`)).value;
    return {
      clientSecret: await secret(o.spec.apiClientId),
      adminClientSecret: await secret(o.spec.adminClientId),
    };
  }
}

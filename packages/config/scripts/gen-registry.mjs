// Generate src/settings/registry.generated.ts from settings-tree.yaml (IPB-07-36, PL1 decision D-12).
// `--check` fails when the committed file is stale (CI).
import { readFileSync, writeFileSync } from "node:fs";
import { parse } from "yaml";

const root = new URL("../", import.meta.url);
const doc = parse(readFileSync(new URL("settings-tree.yaml", root), "utf8"));
const TIERS = ["PLATFORM", "PLAN", "BRAND", "TENANT", "ENTITY", "USER"];
const TYPES = [
  "bool",
  "int",
  "decimal",
  "string",
  "enum",
  "string[]",
  "enum[]",
  "cidr[]",
  "json",
  "locale",
  "route",
  "time",
  "range",
  "date",
];
const errors = [];
const seen = new Set();

function tsType(k) {
  let t;
  switch (k.type) {
    case "bool":
      t = "boolean";
      break;
    case "int":
    case "decimal":
      t = "number";
      break;
    case "enum":
      t = k.values.map((v) => JSON.stringify(v)).join(" | ");
      break;
    case "enum[]":
      t = `Array<${k.values.map((v) => JSON.stringify(v)).join(" | ")}>`;
      break;
    case "string[]":
    case "cidr[]":
      t = "string[]";
      break;
    case "json":
      t = "JsonValue";
      break;
    default:
      t = "string";
  }
  return k.default === null || k.default === undefined ? `${t} | null` : t;
}

for (const k of doc.keys) {
  if (seen.has(k.key)) errors.push(`duplicate key ${k.key}`);
  seen.add(k.key);
  if (!/^[a-z][a-z0-9_]*(\.([a-z0-9_]+|\{[a-z_]+\}[a-z0-9_]*))+$/.test(k.key))
    errors.push(`bad key ${k.key}`);
  if (!TIERS.includes(k.tier)) errors.push(`${k.key}: bad tier ${k.tier}`);
  if (!TYPES.includes(k.type)) errors.push(`${k.key}: bad type ${k.type}`);
  if ((k.type === "enum" || k.type === "enum[]") && !Array.isArray(k.values))
    errors.push(`${k.key}: enum needs values`);
  if (!k.locked && !Array.isArray(k.change))
    errors.push(`${k.key}: change roles required unless locked`);
  if (!k.source) errors.push(`${k.key}: source required`);
  if (k.mc_deactivate && (!["R2", "R4"].includes(k.mc_deactivate) || k.type !== "bool" || k.mc))
    errors.push(`${k.key}: mc_deactivate is R2 or R4 on a bool key without mc`);
  if (k.tighten && !["min", "max", "superset", "subset", true, false].includes(k.tighten))
    errors.push(`${k.key}: bad tighten ${k.tighten}`);
}
const nodes = doc.tree.map((n) => n.n);
if (nodes.join(",") !== Array.from({ length: 20 }, (_, i) => i + 1).join(","))
  errors.push("tree must list nodes 1..20 in order");
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

const isTemplate = (key) => key.includes("{");
const pattern = (key) =>
  "^" +
  key
    .split(".")
    .map((seg) => seg.replace(/\{[a-z_]+\}/g, "([a-z0-9_-]+)"))
    .join("\\.") +
  "$";
const tsKey = (key) =>
  isTemplate(key) ? "`" + key.replace(/\{[a-z_]+\}/g, "${string}") + "`" : JSON.stringify(key);

const defs = doc.keys.map((k) => {
  const d = {
    key: k.key,
    tier: k.tier,
    type: k.type,
    default: k.default ?? null,
    ...(k.values ? { values: k.values } : {}),
    ...(k.min !== undefined ? { min: k.min } : {}),
    ...(k.max !== undefined ? { max: k.max } : {}),
    locked: Boolean(k.locked),
    ...(k.tighten !== undefined ? { tighten: k.tighten } : {}),
    userOverride: Boolean(k.user_override),
    change: k.change ?? [],
    mc: k.mc ?? false,
    ...(k.mc_deactivate ? { mcDeactivate: k.mc_deactivate } : {}),
    ...(k.help ? { help: k.help } : {}),
    ...(isTemplate(k.key) ? { pattern: pattern(k.key) } : {}),
    source: k.source,
    ...(k.note ? { note: k.note } : {}),
  };
  return d;
});

const exact = doc.keys.filter((k) => !isTemplate(k.key));
const templ = doc.keys.filter((k) => isTemplate(k.key));
const out = `// GENERATED by scripts/gen-registry.mjs from settings-tree.yaml — do not edit by hand.
import type { SettingDef } from "./types.js";

export type JsonValue = null | boolean | number | string | JsonValue[] | { [k: string]: JsonValue };

export const SETTINGS_TREE_VERSION = ${JSON.stringify(String(doc.version))};

export const SETTINGS_TREE = ${JSON.stringify(doc.tree, null, 2)} as const;

export const CONSOLE_TREE = ${JSON.stringify(doc.console_tree, null, 2)} as const;

export const SETTING_DEFS: readonly SettingDef[] = ${JSON.stringify(defs, null, 2)};

/** Value type per registered key. Templated keys use template-literal index signatures. */
export type SettingValueMap = {
${exact.map((k) => `  ${tsKey(k.key)}: ${tsType(k)};`).join("\n")}
} & {
${templ.map((k) => `  [k: ${tsKey(k.key)}]: ${tsType(k)};`).join("\n")}
};

/** Every key code may read. An unregistered key fails typecheck (IPB-01 §01.5, @IPB-07-AT-05). */
export type SettingKey = keyof SettingValueMap & string;
`;
const file = new URL("src/settings/registry.generated.ts", root);
if (process.argv.includes("--check")) {
  let cur = "";
  try {
    cur = readFileSync(file, "utf8");
  } catch {}
  if (cur !== out) {
    console.error(
      "src/settings/registry.generated.ts is stale; run pnpm --filter @infrabyx/config gen:registry",
    );
    process.exit(1);
  }
  console.log(`settings registry up to date (${defs.length} keys)`);
} else {
  writeFileSync(file, out);
  console.log(`wrote ${defs.length} keys`);
}
